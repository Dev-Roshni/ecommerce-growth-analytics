--Part 1 — Basic Data & Customer Overview

--1.How many total customers/rows are in the dataset?
SELECT COUNT(*) FROM Customers_Clean;

--2.How many unique customers are there?
SELECT COUNT(DISTINCT Customer_id)
FROM Customers_Clean;

--3. What is the date range of customer activity?
/*Earliest first_order_date
Latest Last_order_date
*/
SELECT 
MIN(first_order_date) AS Earliest_order_date,
MAX(first_order_date) AS Latest_order_date
FROM Customers_Clean;

--4. What is the average number of orders per customer?
SELECT 
MIN(total_orders),
MAX(total_orders),
AVG(total_orders)
FROM Customers_Clean;

--5. What is the minimum, maximum and average customer spend on order?
SELECT 
MIN(total_revenue) AS MIN_Revenue,
MAX(total_revenue) AS MAX_Revenue,
ROUND(AVG(total_revenue),2) AS Average_Revenue
FROM Customers_Clean;

--6. What is the minimum, maximum and average Average order value
SELECT 
MIN(average_order_value) AS MIN_average_order_value,
MAX(average_order_value) AS MAX_average_order_value,
ROUND(AVG(average_order_value),2) AS average_order_value
FROM Customers_Clean;

--7. How many customers fall into each City Tier?
SELECT Tier,
COUNT(*) AS Customer_Count
FROM Customers_Clean
GROUP BY Tier
ORDER BY Customer_Count DESC;

--8. How many customers are there in each city?
SELECT City,
COUNT(*) AS Customer_Count
FROM Customers_Clean
GROUP BY City
ORDER BY Customer_Count DESC;

--9. What percentage of customers belong to each City Tier?
SELECT Tier,
COUNT(*) AS Customer_Count,
ROUND(COUNT(*)*100.0/SUM(COUNT(*)) OVER(),2) AS Percentage
