--Part 4 — Acquisition Channel, City/Tier & Business

--31. How many customers came from each acquisition channel?
SELECT acquisition_channel,
COUNT(*) AS Customer_count
FROM Customers_Clean
GROUP BY acquisition_channel
ORDER BY Customer_Count DESC;

--32.What percentage of customers came from each acquisition channel?
SELECT acquisition_channel,
COUNT(*) AS Customer_count,
ROUND(COUNT(*)*100/SUM(COUNT(*)) OVER(),2) AS Percentage
FROM Customers_Clean
GROUP BY acquisition_channel
ORDER BY Customer_Count DESC;

--33. Which acquisition channel generated the highest total revenue?
SELECT acquisition_channel,
COUNT(*) AS Customer_count,
SUM(total_revenue) AS Total_revenue,
ROUND(COUNT(*)*100/SUM(COUNT(*)) OVER(),2) AS Percentage
FROM Customers_Clean
GROUP BY acquisition_channel
ORDER BY Total_revenue DESC;

--34. Which acquisition channel has the highest average revenue per customer?
SELECT acquisition_channel,
COUNT(*) AS Customer_count,
SUM(total_revenue) AS Total_revenue,
ROUND(AVG(total_revenue),2) AS avg_revenue_per_customer ,
ROUND(COUNT(*)*100/SUM(COUNT(*)) OVER(),2) AS Percentage
FROM Customers_Clean
GROUP BY acquisition_channel
ORDER BY avg_revenue_per_customer  DESC;

--35. Which acquisition channel has the highest repurchase rate?
SELECT acquisition_channel,
COUNT(*) AS Total_Customer,
COUNT(*) FILTER(WHERE repurchased = 'Y') AS repurchased_customers,
ROUND(
COUNT(*)FILTER(WHERE repurchased = 'Y')*100.0/COUNT(*),2)
AS repurchased_rate
FROM Customers_Clean
GROUP BY acquisition_channel
ORDER BY repurchased_rate  DESC;

--36. Compare customer behavior across City Tiers.
SELECT Tier,
COUNT(*) AS Customer_Count,
