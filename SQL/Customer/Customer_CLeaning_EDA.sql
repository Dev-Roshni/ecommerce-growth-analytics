--Part 3 — Repurchase & Customer Behavior
--21. How many customers repurchased and how many did not repurchase?

SELECT  repurchased,
COUNT(*) AS Customer_count
FROM Customers_Clean
GROUP BY repurchased
ORDER BY Customer_count ;

--22 What percentage of customers repurchased?
SELECT  repurchased,
COUNT(*) AS Customer_count,
ROUND(COUNT(*)*100/SUM(COUNT(*)) OVER(),2) AS Percentage
FROM Customers_Clean
GROUP BY repurchased
ORDER BY Customer_count ;

--23. What percentage of customers did NOT repurchase?
SELECT
    COUNT(*) AS non_repurchased_customers,
    ROUND(
        COUNT(*) * 100.0 /
        (SELECT COUNT(*) FROM customers_clean),
        2
    ) AS non_repurchase_percentage
FROM customers_clean
WHERE repurchased = 'N';
--24 What is the average time taken for customers to make their second purchase?

SELECT 
ROUND(AVG(time_to_2nd_purchase),2) AS avg_days_to_2nd_purchase
FROM Customers_Clean;


--25. What are the minimum, maximum and average days taken for the second purchase?
SELECT
    MIN(time_to_2nd_purchase) AS min_days,
    MAX(time_to_2nd_purchase) AS max_days,
    ROUND(AVG(time_to_2nd_purchase), 2) AS avg_days
FROM customers_clean;
--26. How many customers made their second purchase within 30 days?
SELECT 
COUNT(*) AS NumberOf_Customer
FROM Customers_Clean
WHERE time_to_2nd_purchase <= 30;

--27. What percentage of customers made their second purchase within 30 days?
SELECT
    COUNT(*) AS customers_within_30_days,
    ROUND(
        COUNT(*) * 100.0 /
        (
            SELECT COUNT(time_to_2nd_purchase)
            FROM customers_clean
        ),
        2
    ) AS percentage_within_30_days
FROM customers_clean
WHERE time_to_2nd_purchase <= 30;

--28. Compare revenue between repurchased and non-repurchased Customer
